// Latin storage code -> Cyrillic code shown in the UI (e.g. SPR-03 -> СПР-03)
export function toCyrillicCode(code: string): string {
  return code
    .replace('PRCH', 'ПРЧ').replace('SPR', 'СПР').replace('PRK', 'ПРК').replace('PRD', 'ПРД')
    .replace('OTV', 'ОТВ').replace('AKT', 'АКТ').replace('ZKL', 'ЗКЛ').replace('RSH', 'РШ')
    .replace('ZHR', 'ЖР').replace('KR', 'КР').replace('UV', 'УВ').replace('SP', 'СП')
    .replace('RP', 'РП').replace('SZ', 'СЗ').replace('ZP', 'ЗП').replace('TR', 'ТР')
    .replace('OB', 'ОБ').replace('RD', 'РД').replace('OP', 'ОП').replace('LO', 'ЛО')
    .replace('PL', 'ПЛ');
}

